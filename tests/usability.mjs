import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('test-results', { recursive: true });
try {
  await page.goto('http://127.0.0.1:5173');
  let releaseModel, modelStarted;
  const requested = new Promise(resolve => { modelStarted = resolve; });
  const released = new Promise(resolve => { releaseModel = resolve; });
  await page.route('**/ocr/lang/**', async route => {
    modelStarted();
    await released;
    await route.continue();
  });
  await page.click('#analyze');
  await requested;
  await page.click('#cancel-analysis');
  await page.waitForFunction(() => !document.querySelector('#analyze').disabled);
  assert.match(await page.locator('#pipeline-status').textContent(), /cancelled/);
  assert.equal(await page.locator('#result-actions').isVisible(), false);
  releaseModel();
  await page.unrouteAll({ behavior: 'wait' });
  await page.click('#analyze');
  await page.waitForFunction(() => document.querySelector('#output-status').textContent === 'READY TO EXPLORE', {}, { timeout: 90000 });
  await page.click('[data-mode="table"]');
  const first = page.locator('[data-value="0"]');
  await first.fill('31');
  await first.press('Tab');
  assert.equal(await page.locator('[data-label="1"]').evaluate(el => el === document.activeElement), true, 'Editing must keep keyboard focus in the table');
  assert.equal(await page.locator('#undo-edits').isEnabled(), true);
  await page.locator('#chart-title').fill('Reviewed harvest');
  await page.locator('#chart-title').press('Tab');
  await page.locator('#chart-unit').fill('boxes');
  await page.locator('#chart-unit').press('Tab');
  assert.match(await page.locator('.chart-heading h3').textContent(), /Reviewed harvest/);
  assert.match(await page.locator('.chart-heading p').textContent(), /boxes/);
  await page.click('#copy-summary');
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.match(copied, /Reviewed harvest/);
  assert.match(copied, /31 boxes/);
  await page.click('#undo-edits');
  assert.equal(await first.inputValue(), '24');
  assert.equal(await page.locator('#chart-unit').inputValue(), 'kg');
  assert.equal(await page.locator('#undo-edits').isEnabled(), false);
  await page.click('[data-mode="chart"]');
  await page.screenshot({ path: 'test-results/usability-desktop.png', fullPage: true });
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  assert.deepEqual(axe.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), []);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/usability-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);

  const failureContext = await browser.newContext();
  const failurePage = await failureContext.newPage();
  failurePage.on('pageerror', error => errors.push(error.message));
  await failurePage.route('**/ocr/lang/**', route => route.fulfill({ status: 503, body: 'Temporarily unavailable' }));
  await failurePage.goto('http://127.0.0.1:5173');
  await failurePage.click('#analyze');
  await failurePage.waitForFunction(() => !document.querySelector('#analyze').disabled, {}, { timeout: 15000 });
  assert.equal(await failurePage.locator('#retry').isVisible(), true);
  assert.match(await failurePage.locator('#error').textContent(), /reader could not/);
  await failurePage.unrouteAll();
  await failurePage.click('#retry');
  await failurePage.waitForFunction(() => document.querySelector('#output-status').textContent === 'READY TO EXPLORE', {}, { timeout: 90000 });
  assert.equal(await failurePage.locator('#retry').isVisible(), false);
  assert.deepEqual(errors, []);
  await failureContext.close();
  console.log('Cancel, retry after model failure, keyboard editing, undo, copy, responsive layout, and accessibility passed.');
} finally {
  await browser.close();
}
